s32 Hyrule_GetRestrictionOot(PlayState* play, HyruleRestrictionOot restriction) {
    s32 ootScene = Hyrule_GetOotSceneId(play->sceneId);
    s32 i;

    if (ootScene < 0) {
        return -1;
    }
    for (i = 0; i < ARRAY_COUNT(sRestrictionFlagsOot); i++) {
        if (sRestrictionFlagsOot[i].ootScene == ootScene) {
            switch (restriction) {
                case HYRULE_RESTRICTION_OCARINA_OOT:
                    return (sRestrictionFlagsOot[i].flags2 >> 2) & 3;
                case HYRULE_RESTRICTION_WARP_SONGS_OOT:
                    return sRestrictionFlagsOot[i].flags2 & 3;
                case HYRULE_RESTRICTION_FARORES_OOT:
                    return (sRestrictionFlagsOot[i].flags3 >> 4) & 3;
                case HYRULE_RESTRICTION_DINS_NAYRUS_OOT:
                    return (sRestrictionFlagsOot[i].flags3 >> 2) & 3;
            }
        }
    }
    return 0;
}
