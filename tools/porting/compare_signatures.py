#!/usr/bin/env python3
"""Compare the header function signatures of SoH and 2Ship, as extracted by extract_decls.py.

Types are normalized before comparison: typedefs of plain scalars are expanded (s32 -> int) and
`struct X` is written as `X`. Differences are then classified per shared function name, and the result
is written as JSON (for translation scripts) and Markdown (for people).
"""
import argparse
import json
import re
from collections import Counter, defaultdict

SCALARS = {
    "char", "signed char", "unsigned char", "short", "unsigned short", "int", "unsigned int", "long",
    "unsigned long", "long long", "unsigned long long", "float", "double", "long double", "_Bool", "void",
}
IDENT = re.compile(r"[A-Za-z_]\w*")


def scalar_typedefs(typedefs):
    """Maps each typedef that resolves to a plain scalar to that scalar."""
    resolved = {}
    for name in typedefs:
        seen, t = set(), name
        while t in typedefs and t not in seen:
            seen.add(t)
            t = typedefs[t]
        t = " ".join(t.split())
        if t in SCALARS:
            resolved[name] = t
    return resolved


def normalize(t, scalars):
    t = re.sub(r"\bstruct\s+|\bunion\s+|\benum\s+", "", t)
    t = IDENT.sub(lambda m: scalars.get(m.group(0), m.group(0)), t)
    t = re.sub(r"\s*\*\s*", "*", " ".join(t.split()))
    return t


def signature(fn, scalars):
    return normalize(fn["ret"], scalars), [normalize(p["type"], scalars) for p in fn["params"]], fn["variadic"]


def spelled(fn):
    return " ".join(fn["ret"].split()), [" ".join(p["type"].split()) for p in fn["params"]], fn["variadic"]


def classify(soh, mm, soh_scalars, mm_scalars):
    if spelled(soh) == spelled(mm):
        return "identical", {}
    s_ret, s_params, s_var = signature(soh, soh_scalars)
    m_ret, m_params, m_var = signature(mm, mm_scalars)
    if (s_ret, s_params, s_var) == (m_ret, m_params, m_var):
        return "spelling", {}
    detail = {}
    if s_ret != m_ret:
        detail["return"] = [s_ret, m_ret]
    if len(s_params) != len(m_params) or s_var != m_var:
        detail["arity"] = [len(s_params), len(m_params)]
    changed = [i for i, (a, b) in enumerate(zip(s_params, m_params)) if a != b]
    if changed:
        detail["params"] = {i: [s_params[i], m_params[i]] for i in changed}
    if "arity" in detail:
        kind = "arity"
    elif "return" in detail and not changed:
        kind = "return"
    else:
        kind = "params"
    return kind, detail


def render(fn):
    params = ", ".join(" ".join(p["type"].split()) for p in fn["params"]) or "void"
    if fn["variadic"]:
        params += ", ..."
    return f"{' '.join(fn['ret'].split())} {{name}}({params})"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("soh")
    parser.add_argument("mm")
    parser.add_argument("--json", required=True)
    parser.add_argument("--markdown", required=True)
    args = parser.parse_args()

    soh, mm = json.load(open(args.soh)), json.load(open(args.mm))
    soh_scalars, mm_scalars = scalar_typedefs(soh["typedefs"]), scalar_typedefs(mm["typedefs"])
    shared = sorted(set(soh["functions"]) & set(mm["functions"]))

    results = {}
    for name in shared:
        kind, detail = classify(soh["functions"][name], mm["functions"][name], soh_scalars, mm_scalars)
        results[name] = {
            "kind": kind, "detail": detail,
            "soh": render(soh["functions"][name]).format(name=name), "soh_file": soh["functions"][name]["file"],
            "mm": render(mm["functions"][name]).format(name=name), "mm_file": mm["functions"][name]["file"],
        }
    counts = Counter(r["kind"] for r in results.values())
    differing = {n: r for n, r in results.items() if r["kind"] not in ("identical", "spelling")}

    with open(args.json, "w") as f:
        json.dump({"soh_only": len(set(soh["functions"]) - set(mm["functions"])),
                   "mm_only": len(set(mm["functions"]) - set(soh["functions"])),
                   "shared": len(shared), "counts": counts, "functions": results}, f, indent=1, sort_keys=True)

    by_header = defaultdict(list)
    for name, r in differing.items():
        by_header[r["mm_file"]].append(name)
    titles = {"arity": "parameter count", "return": "return type", "params": "parameter types"}
    lines = [
        "# SoH and 2Ship engine signature differences",
        "",
        "Generated by `tools/porting/compare_signatures.py` from the function declarations in SoH's",
        "`soh/include` and 2Ship's `mm/include` headers. Do not edit by hand; see `tools/porting/README.md`.",
        "",
        "| | Functions |",
        "|---|---|",
        f"| Declared in SoH headers | {len(soh['functions'])} |",
        f"| Declared in 2Ship headers | {len(mm['functions'])} |",
        f"| Declared in both | {len(shared)} |",
        f"| Identical | {counts['identical']} |",
        f"| Same types, spelled differently (`s32` vs `int`) | {counts['spelling']} |",
        f"| **Different signatures** | **{len(differing)}** |",
        f"| ... parameter count | {counts['arity']} |",
        f"| ... parameter types | {counts['params']} |",
        f"| ... return type only | {counts['return']} |",
        "",
        "Types below are normalized: scalar typedefs are expanded and `struct` is dropped.",
        "",
    ]
    for header in sorted(by_header):
        lines += [f"## {header}", "", "| Function | Difference | SoH | 2Ship |", "|---|---|---|---|"]
        for name in sorted(by_header[header]):
            r = results[name]
            d = r["detail"]
            parts = []
            if "arity" in d:
                parts.append(f"{d['arity'][0]} vs {d['arity'][1]} params")
            if "return" in d:
                parts.append(f"returns `{d['return'][0]}` vs `{d['return'][1]}`")
            for i, (a, b) in sorted(d.get("params", {}).items()):
                parts.append(f"param {i}: `{a}` vs `{b}`")
            lines.append(f"| `{name}` | {titles[r['kind']]}: {'; '.join(parts)} | `{r['soh']}` | `{r['mm']}` |")
        lines.append("")
    with open(args.markdown, "w") as f:
        f.write("\n".join(lines))

    print(f"SoH {len(soh['functions'])}, 2Ship {len(mm['functions'])}, shared {len(shared)}: " +
          ", ".join(f"{k} {v}" for k, v in sorted(counts.items())) + f"; differing {len(differing)}")


if __name__ == "__main__":
    main()
