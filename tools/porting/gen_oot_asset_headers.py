#!/usr/bin/env python3
"""Generate OoT asset headers for ported code from SoH's, with paths under oot/ as in oot.o2r.

Headers are written to hyrule/assets/oot/<dir>/<name>/<name>.h, so OoT code includes
"assets/oot/objects/object_kusa/object_kusa.h" and cannot pick up MM's header of the same name.

    python3 tools/porting/gen_oot_asset_headers.py ../Shipwright/soh/assets objects/gameplay_keep objects/object_kusa
"""
import argparse
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, "..", "..", "hyrule", "assets", "oot")


def convert(text, rel):
    guard = "OOT_" + re.sub(r"\W", "_", rel).upper() + "_H"
    text = re.sub(r"^#ifndef \w+\n#define \w+( 1)?$", f"#ifndef {guard}\n#define {guard} 1", text, count=1, flags=re.M)
    text = text.replace('"__OTR__', '"__OTR__oot/')
    note = f"// Generated by tools/porting/gen_oot_asset_headers.py from SoH's soh/assets/{rel}/. Do not edit by hand.\n"
    return note + text


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("soh_assets", help="SoH's soh/assets directory")
    parser.add_argument("dirs", nargs="+", help="asset directories relative to soh_assets, e.g. objects/object_kusa, "
                        "or header files, e.g. scenes/overworld/spot05/spot05_scene.h")
    args = parser.parse_args()
    for rel in args.dirs:
        rel = rel.strip("/")
        if rel.endswith(".h"):
            # A header named apart from its directory (scenes: scenes/overworld/spot05/spot05_scene.h).
            text = open(os.path.join(args.soh_assets, rel)).read()
            out = os.path.join(OUT_DIR, rel)
            rel = rel[: -len(".h")]
        else:
            name = os.path.basename(rel)
            text = open(os.path.join(args.soh_assets, rel, name + ".h")).read()
            out = os.path.join(OUT_DIR, rel, name + ".h")
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w") as f:
            f.write(convert(text, rel))
        print(os.path.normpath(out))


if __name__ == "__main__":
    main()
