#!/usr/bin/env python3
"""Generate hyrule/HyruleFlags.h: OoT's event flag names and accessors, from SoH's z64save.h.

Every EVENTCHKINF_, ITEMGETINF_, INFTABLE_ and EVENTINF_ define gets an _Oot suffix (MM has flags of
the same names), and so does every such name it refers to. Multi-line helper macros are left out.

    python3 tools/porting/gen_oot_flags.py ../Shipwright/soh/include/z64save.h
"""
import argparse
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "hyrule", "HyruleFlags.h")
NAME = re.compile(r"\b((?:EVENTCHKINF|ITEMGETINF|INFTABLE|EVENTINF)_\w+)")
DEFINE = re.compile(r"^#define (EVENTCHKINF|ITEMGETINF|INFTABLE|EVENTINF)_\w+[ (]")

HEADER = """#pragma once

// 3Ship [Hyrule] OoT's event flags, kept in the save's eventChkInfOot, itemGetInfOot and infTableOot
// (and the unsaved eventInfOot). See hyrule/README.md.
//
// Generated by tools/porting/gen_oot_flags.py from SoH's z64save.h. Do not edit by hand.

#define OOT_FLAG_GET(array, flag) ((array)[(flag) >> 4] & (1 << ((flag) & 0xF)))
#define OOT_FLAG_SET(array, flag) ((array)[(flag) >> 4] |= (1 << ((flag) & 0xF)))
#define OOT_FLAG_CLEAR(array, flag) ((array)[(flag) >> 4] &= ~(1 << ((flag) & 0xF)))

#define GET_EVENTCHKINF_OOT(flag) OOT_FLAG_GET(gSaveContext.save.saveInfo.eventChkInfOot, flag)
#define SET_EVENTCHKINF_OOT(flag) OOT_FLAG_SET(gSaveContext.save.saveInfo.eventChkInfOot, flag)
#define CLEAR_EVENTCHKINF_OOT(flag) OOT_FLAG_CLEAR(gSaveContext.save.saveInfo.eventChkInfOot, flag)
#define GET_ITEMGETINF_OOT(flag) OOT_FLAG_GET(gSaveContext.save.saveInfo.itemGetInfOot, flag)
#define SET_ITEMGETINF_OOT(flag) OOT_FLAG_SET(gSaveContext.save.saveInfo.itemGetInfOot, flag)
#define CLEAR_ITEMGETINF_OOT(flag) OOT_FLAG_CLEAR(gSaveContext.save.saveInfo.itemGetInfOot, flag)
#define GET_INFTABLE_OOT(flag) OOT_FLAG_GET(gSaveContext.save.saveInfo.infTableOot, flag)
#define SET_INFTABLE_OOT(flag) OOT_FLAG_SET(gSaveContext.save.saveInfo.infTableOot, flag)
#define CLEAR_INFTABLE_OOT(flag) OOT_FLAG_CLEAR(gSaveContext.save.saveInfo.infTableOot, flag)
#define GET_EVENTINF_OOT(flag) OOT_FLAG_GET(gSaveContext.eventInfOot, flag)
#define SET_EVENTINF_OOT(flag) OOT_FLAG_SET(gSaveContext.eventInfOot, flag)
#define CLEAR_EVENTINF_OOT(flag) OOT_FLAG_CLEAR(gSaveContext.eventInfOot, flag)
// SoH's multi-line GET_EVENTCHKINF_CARPENTERS_FREE_ALL: all four carpenters freed from the Gerudo.
#define GET_EVENTCHKINF_CARPENTERS_FREE_ALL_OOT() \
    ((gSaveContext.save.saveInfo.eventChkInfOot[9] & 0xF) == 0xF)

"""


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("soh_z64save", help="SoH's soh/include/z64save.h")
    args = parser.parse_args()

    lines = open(args.soh_z64save).read().splitlines()
    out = [HEADER]
    count = 0
    for line in lines:
        if not DEFINE.match(line) or line.rstrip().endswith("\\"):
            continue
        out.append(NAME.sub(r"\1_Oot", line.split("//")[0].rstrip()))
        count += 1
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"{count} flag defines written to {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
