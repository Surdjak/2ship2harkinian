#!/usr/bin/env python3
"""Generate hyrule/HyruleGetItemTable.inc, OoT's get-item table with 3Ship's unified ids, from SoH's.

    python3 tools/porting/gen_oot_get_items.py ../Shipwright/soh

Each OoT entry (SoH's VanillaItemTable_Init in soh/OTRGlobals.cpp) becomes a GetItemEntry indexed by its OoT
get-item id: OoT's item, object and draw ids get the _Oot suffix, the text id becomes TEXT_OOT(id), and the
collectible drop type in the field is converted to MM's En_Item00 type as Item00_FromOot does.
"""

import argparse
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
OUT = os.path.join(ROOT, "hyrule", "HyruleGetItemTable.inc")

# OoT's En_Item00 types to MM's (hyrule/HyruleActor.c Item00_FromOot; 0x18 is MM's ITEM00_NOTHING).
ITEM00_FROM_OOT = [0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x05, 0x05, 0x08, 0x0B, 0x0C,
                   0x0D, 0x0E, 0x0F, 0x1E, 0x11, 0x12, 0x13, 0x14, 0x16, 0x16, 0x18, 0x18, 0x04]

CHEST_ANIMS = {"CHEST_ANIM_SHORT": "CHEST_ANIM_SHORT", "CHEST_ANIM_LONG": "CHEST_ANIM_LONG"}


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("soh", help="SoH's soh directory (the one holding soh/OTRGlobals.cpp)")
    args = parser.parse_args()

    src = open(os.path.join(args.soh, "soh", "OTRGlobals.cpp")).read()
    body = src[src.index("void VanillaItemTable_Init()") :]
    body = body[: body.index("};")]
    items = open(os.path.join(ROOT, "mm", "include", "tables", "item_id_oot.h")).read()
    gis = open(os.path.join(ROOT, "mm", "include", "tables", "get_item_id_oot.h")).read()

    lines = [
        "// 3Ship [Hyrule] OoT's get-item table, indexed by OoT get-item id (GI_*_Oot - GI_OOT_BASE).",
        "//",
        "// Generated by tools/porting/gen_oot_get_items.py from SoH's VanillaItemTable_Init. Do not edit by hand.",
    ]
    count = 0
    for args_text in re.findall(r"GET_ITEM\(([^)]*)\)", body):
        a = [x.strip() for x in args_text.split(",")]
        item, obj, gid, text, field, anim, gi = a[0], a[1], a[2], a[3], a[4], a[5], a[8]
        if f"{gi}_Oot " not in gis:
            raise SystemExit(f"unknown get-item id {gi}")
        item_id = "ITEM_NONE" if item == "ITEM_NONE" or f"{item}_Oot " not in items else f"{item}_Oot"
        field_value = int(field, 16)
        drop = field_value & 0x1F
        if not (field_value & 0x80) and drop < len(ITEM00_FROM_OOT):
            field_value = (field_value & 0xE0) | ITEM00_FROM_OOT[drop]
        lines.append(f"    [{gi}_Oot - GI_OOT_BASE] = GET_ITEM({item_id}, {obj}_Oot, {gid}_Oot, TEXT_OOT({text}), "
                     f"0x{field_value:02X}, {CHEST_ANIMS[anim]}),")
        count += 1
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{count} entries written to {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
