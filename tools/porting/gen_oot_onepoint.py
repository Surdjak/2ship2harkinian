#!/usr/bin/env python3
"""Generate hyrule/HyruleOnePointInfo.inc and HyruleOnePointData.inc from SoH's z_onepointdemo.c and
z_onepointdemo_data.inc: OoT's OnePointCutscene_SetInfo and its keyframes, with MM's names, for hyrule/HyruleOnePoint.c.

    python3 tools/porting/gen_oot_onepoint.py ../Shipwright/soh/src/code
"""
import argparse
import os
import re

parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
parser.add_argument("soh_code", help="SoH's soh/src/code directory")
args = parser.parse_args()
SOH = args.soh_code.rstrip("/") + "/"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "hyrule") + "/"

def common(s):
    s = re.sub(r"\bD_80([0-9A-F]{6})\b", r"D_80\1Oot", s)
    s = s.replace("CutsceneCameraPoint ", "CutsceneCameraPointOot ").replace("CutsceneCameraPoint*", "CutsceneCameraPointOot*")
    s = s.replace("OnePointCsFull ", "OnePointCsFullOot ")
    s = re.sub(r"\bCS_CMD_CONTINUE\b", "CS_CMD_CONTINUE_Oot", s)
    s = re.sub(r"\bCS_CMD_STOP\b", "CS_CMD_STOP_Oot", s)
    return s

# Data
d = open(SOH + "z_onepointdemo_data.inc").read()
d = d.replace('#include "global.h"\n', "")
d = common(d)
hdr = ("// 3Ship [Hyrule] OoT's one-point cutscene data (SoH's z_onepointdemo_data.inc), included by HyruleOnePoint.c.\n"
       "// Generated by tools/porting/gen_oot_onepoint.py from SoH's file: the D_80 names take an Oot suffix. Do not edit by hand.\n")
open(OUT + "HyruleOnePointData.inc", "w").write(hdr + d)

# SetInfo body
src = open(SOH + "z_onepointdemo.c").read().splitlines()
start = next(i for i, l in enumerate(src) if l.startswith("s32 OnePointCutscene_SetInfo("))
end = next(i for i in range(start, len(src)) if src[i] == "}")
body = "\n".join(src[start:end + 1])
body = common(body)
reps = [
    ("s32 OnePointCutscene_SetInfo(PlayState* play, s16 camIdx, s16 csId, Actor* actor, s16 timer) {",
     "static s32 OnePointCutscene_SetInfoOot(PlayState* play, s16 camIdx, s16 csId, Actor* actor, s16 timer) {"),
    ("Camera* childCam = play->cameraPtrs[csCam->childCamIdx];", "OnePointCamOot* att = &sCamsOot[camIdx];\n    Camera* childCam = play->cameraPtrs[att->childCamId];"),
    ("Unique9OnePointCs* csInfo = ONEPOINT_CS_INFO(csCam);", ""),
    ("csInfo->", "att->"),
    ("csCam->timer", "att->timer"),
    ("csCam->childCamIdx", "att->childCamId"),
    ("SUBCAM_FREE", "CAM_ID_MAIN"),
    ("Player* player = mainCam->player;", "Player* player = GET_PLAYER(play);"),
    ("csCam->unk_14C |= 2;", "// OoT's unk_14C bit 2 only turns off its water camera."),
    ("csCam->data2 = 0xC;", "// OoT's Camera_Keep4 is not ported (CAM_SET_TURN_AROUND)."),
    ("play->view.lookAt", "play->view.at"),
    ("Sfx_PlaySfxCentered(", "Audio_PlaySfx("),
    ("CAM_STAT_UNK3", "CAM_STATUS_UNK3"),
    ("PLAYER_STATE1_IN_CUTSCENE", "PLAYER_STATE1_20000000"),
    ("PLAYER_STATE1_IN_WATER", "PLAYER_STATE1_8000000"),
    ("!LINK_IS_ADULT", "!LINK_IS_ADULT_OOT"),
    ("(LINK_IS_ADULT)", "(LINK_IS_ADULT_OOT)"),
    ("Player_SetCsActionWithHaltedActors(", "Player_SetCsActionWithHaltedActorsOot("),
    ("Quake_Add(", "Quake_Request("),
    ("Quake_SetQuakeValues(", "Quake_SetPerturbations("),
    ("Quake_SetCountdown(", "Quake_SetDuration("),
    ("Camera_RequestMode(", "Camera_ChangeMode("),
    ("OnePointCutscene_SetCsCamPoints(csCam,", "OnePointCutscene_SetCsCamPointsOot(att,"),
    ("OnePointCutscene_EndCutscene(", "OnePointCutscene_EndCutscene("),
]
for a, b in reps:
    body = body.replace(a, b)
body = re.sub(r"(?<![A-Za-z_])Player_SetCsAction\(", "Player_SetCsActionOot(", body)
body = re.sub(r"func_800C0808\(play, camIdx, [^,]+, CAM_SET_(\w+)\)", r"OnePoint_SetSettingOot(play, camIdx, ONEPOINT_SET_\1)", body)
body = re.sub(r"Play_CameraChangeSetting\(play, camIdx, CAM_SET_(\w+)\)", r"OnePoint_SetSettingOot(play, camIdx, ONEPOINT_SET_\1)", body)
body = body.replace("Play_CameraChangeSetting(play, CAM_ID_MAIN,", "Play_ChangeCameraSetting(play, CAM_ID_MAIN,")
body = body.replace("Play_CameraSetAtEye(", "OnePoint_SetAtEyeOot(")
body = re.sub(r"Play_CameraSetFov\(play, camIdx, ([^;]+)\);", r"csCam->fov = \1;", body)
body = re.sub(r"Play_SetCameraRoll\(play, camIdx, ([^;]+)\);", r"csCam->roll = \1;", body)
body = re.sub(r"OLib_Vec3fDiffToVecSphGeo\(&(\w+), ([^;]+)\);", r"\1 = OLib_Vec3fDiffToVecGeo(\2);", body)
body = re.sub(r"OLib_VecSphGeoToVec3f\(&([^,]+), ([^;]+)\);", r"\1 = OLib_VecGeoToVec3f(\2);", body)
for fn in ("Actor_GetFocus", "Actor_GetWorldPosShapeRot", "Actor_GetWorld"):
    body = re.sub(fn + r"\(&(\w+), ([^;]+)\);", r"\1 = " + fn + r"(\2);", body)
body = re.sub(r"\bVecSph\b", "VecGeo", body)
body = re.sub(r"if \(GameInteractor_Should\(VB_\w+, true[^{]*\{", "{", body)
body = re.sub(r"\n\s*osSyncPrintf\([^;]*;", "", body)
open(OUT + "HyruleOnePointInfo.inc", "w").write(
    "// 3Ship [Hyrule] OoT's OnePointCutscene_SetInfo (SoH's z_onepointdemo.c), included by HyruleOnePoint.c.\n"
    "// Generated by tools/porting/gen_oot_onepoint.py from SoH's file, with MM's names. Do not edit by hand.\n\n" + body + "\n")
print(os.path.normpath(OUT + "HyruleOnePointInfo.inc"))
print(os.path.normpath(OUT + "HyruleOnePointData.inc"))
