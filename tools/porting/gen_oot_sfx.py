#!/usr/bin/env python3
"""Generate OoT's sound effect tables for 3Ship's OoT sfx banks, from SoH (see hyrule/README.md, Audio).

hyrule/HyruleSfxParams.inc: OoT's per-bank sfx params (SoH's audio_sound_params.c) in MM's SfxParams layout.
OoT's bit 2 (force reset) is MM's SFX_FLAG2_FORCE_RESET; its other bits are MM's.

hyrule/HyruleSfx.h: the sfx names for OoT code (the sources that include it, after MM's sfx.h), as ids in OoT's
banks (SFX_OOT). Ported OoT code names OoT's sounds with MM's names where MM has a sound of that name, and else with
the MM name of OoT's id (which port_actor.py once renamed them to; it now keeps OoT's names). Each name becomes
OoT's sound of that name, or for a name OoT lacks, OoT's sound of its id; OoT's names MM lacks are added. Kept as
MM's: Link's voice (MM's Player speaks in both worlds) and MM's names for ids OoT does not have. Its music names
(NA_BGM_) become OoT's sequences (SEQ_OOT) the same way, but for MM's special ids (stop, disabled, sfx, ambience).

    python3 tools/porting/gen_oot_sfx.py ../Shipwright/soh
"""
import argparse
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
DEFINE = re.compile(r"#define\s+(NA_SE_\w+)\s+(0x[0-9A-Fa-f]+)")
BGM_DEFINE = re.compile(r"#define\s+(NA_BGM_\w+)\s+(0x[0-9A-Fa-f]+)")
# MM's special sequence ids, which OoT code uses as MM's.
BGM_KEPT = {"NA_BGM_STOP", "NA_BGM_DISABLED", "NA_BGM_GENERAL_SFX", "NA_BGM_NATURE_AMBIENCE"}
BANKS = ["Player", "Item", "Env", "Enemy", "System", "Ocarina", "Voice"]
OOT_FORCE_RESET = 1 << 2
MM_SFX_FLAG2_FORCE_RESET = 1 << 0


def defines(path, pattern=DEFINE):
    out = {}
    for name, value in pattern.findall(open(path).read()):
        out.setdefault(name, int(value, 16))
    return out


def gen_params(soh):
    text = open(os.path.join(soh, "src", "code", "audio_sound_params.c")).read()
    lines = [
        "// 3Ship [Hyrule] OoT's sfx params, in MM's SfxParams layout. See hyrule/README.md (Audio).",
        "//",
        "// Generated by tools/porting/gen_oot_sfx.py from SoH's audio_sound_params.c. Do not edit by hand.",
        "",
    ]
    for bank in BANKS:
        body = re.search(r"SoundParams s%sBankParams\[\] = \{(.*?)\n\};" % bank, text, re.S).group(1)
        entries = re.findall(r"\{\s*(0x[0-9A-Fa-f]+|\d+),\s*(0x[0-9A-Fa-f]+|\d+)\s*\}", body)
        lines.append("SfxParams s%sBankParamsOot[] = {" % bank)
        for importance, params in entries:
            params = int(params, 0)
            flags = MM_SFX_FLAG2_FORCE_RESET if params & OOT_FORCE_RESET else 0
            lines.append("    { 0x%02X, 0x%X, 0x%04X }," % (int(importance, 0), flags, params & ~OOT_FORCE_RESET))
        lines.append("};")
        lines.append("")
    open(os.path.join(ROOT, "hyrule", "HyruleSfxParams.inc"), "w").write("\n".join(lines))


def gen_names(soh):
    oot = defines(os.path.join(soh, "include", "sfx.h"))
    mm = defines(os.path.join(ROOT, "mm", "include", "sfx.h"))
    oot_ids = set(oot.values())
    out = []
    for name in sorted(mm):
        if name == "NA_SE_NONE" or name.startswith("NA_SE_VO_LI_"):
            continue
        if name in oot:
            value = oot[name]
        elif mm[name] in oot_ids:
            value = mm[name]
        else:
            continue
        out.append("#undef %s\n#define %s SFX_OOT(0x%04X)" % (name, name, value))
    for name in sorted(oot):
        if name not in mm and name != "NA_SE_NONE":
            out.append("#define %s SFX_OOT(0x%04X)" % (name, oot[name]))
    # OoT's music, the same way: OoT's sequences at SEQ_OOT_BASE.
    oot_bgm = defines(os.path.join(soh, "include", "sequence.h"), BGM_DEFINE)
    mm_bgm = defines(os.path.join(ROOT, "mm", "include", "sequence.h"), BGM_DEFINE)
    oot_seqs = set(oot_bgm.values())
    for name in sorted(mm_bgm):
        if name in BGM_KEPT:
            continue
        if name in oot_bgm:
            value = oot_bgm[name]
        elif mm_bgm[name] in oot_seqs:
            value = mm_bgm[name]
        else:
            continue
        out.append("#undef %s\n#define %s SEQ_OOT(0x%02X)" % (name, name, value))
    for name in sorted(oot_bgm):
        if name not in mm_bgm and name not in BGM_KEPT:
            out.append("#define %s SEQ_OOT(0x%02X)" % (name, oot_bgm[name]))
    header = """#pragma once

// 3Ship [Hyrule] The sound names of OoT code, which includes this after MM's names: its sfx in OoT's banks
// (SFX_OOT) and its music as OoT's sequences (SEQ_OOT). See hyrule/README.md (Audio).
//
// Generated by tools/porting/gen_oot_sfx.py from SoH's and MM's sfx.h. Do not edit by hand.

#include "sfx.h"
#include "sequence.h"
#include "HyruleIds.h"

"""
    open(os.path.join(ROOT, "hyrule", "HyruleSfx.h"), "w").write(header + "\n".join(out) + "\n")
    return len(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("soh", help="SoH's soh/ directory")
    args = parser.parse_args()
    gen_params(args.soh)
    print("names:", gen_names(args.soh))


if __name__ == "__main__":
    main()
