#!/usr/bin/env python3
"""Generate the OoT parts of 2Ship's actor and object tables from SoH's tables.

OoT entries follow MM's in OoT's own order, so a unified id is ACTOR_OOT_BASE or OBJECT_OOT_BASE (see
hyrule/HyruleIds.h) plus the OoT id. Names get an _Oot suffix. Actors that have not been ported are
DEFINE_ACTOR_UNSET, so their ids exist but cannot spawn; a ported actor's line is kept by passing its
OoT enum name to --ported.

    python3 tools/porting/gen_oot_tables.py ../Shipwright/soh/include/tables
"""
import argparse
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, "..", "..", "mm", "include", "tables")
ENTRY = re.compile(r"^/\* (0x[0-9A-Fa-f]+) \*/ (DEFINE_[A-Z_]+)\((.*)\)\s*(//.*)?$")

HEADER = """/**
 * 3Ship [Hyrule] {what} from Ocarina of Time, appended to MM's (see {mm_table}).
 *
 * Generated by tools/porting/gen_oot_tables.py from SoH's {soh_table}. Do not edit by hand.
 * Unified id = {base} (hyrule/HyruleIds.h) + the OoT id shown in each comment.
 */
"""


def entries(path):
    for line in open(path):
        m = ENTRY.match(line.strip())
        if m:
            yield int(m.group(1), 16), m.group(2), [a.strip() for a in m.group(3).split(",")]


def gen_actors(soh_dir, ported):
    lines = [HEADER.format(what="Actors", mm_table="actor_table.h", soh_table="actor_table.h", base="ACTOR_OOT_BASE")]
    expected = 0
    for oot_id, kind, args in entries(os.path.join(soh_dir, "actor_table.h")):
        assert oot_id == expected, f"actor ids must be consecutive (0x{oot_id:X})"
        expected += 1
        enum = args[0] if kind == "DEFINE_ACTOR_UNSET" else args[1]
        enum_oot = f"{enum}_Oot"
        if kind != "DEFINE_ACTOR_UNSET" and enum in ported:
            name, alloc = args[0], args[2]
            lines.append(f'/* 0x{oot_id:03X} */ DEFINE_ACTOR({name}_Oot, {enum_oot}, {alloc}, "{name}_Oot", "{name} (OoT)")')
        else:
            lines.append(f"/* 0x{oot_id:03X} */ DEFINE_ACTOR_UNSET({enum_oot})")
    return "\n".join(lines) + "\n", expected


def gen_objects(soh_dir):
    lines = [HEADER.format(what="Objects", mm_table="object_table.h", soh_table="object_table.h", base="OBJECT_OOT_BASE")]
    expected = 0
    for oot_id, kind, args in entries(os.path.join(soh_dir, "object_table.h")):
        assert oot_id == expected, f"object ids must be consecutive (0x{oot_id:X})"
        expected += 1
        if kind == "DEFINE_OBJECT_UNSET":
            lines.append(f"/* 0x{oot_id:03X} */ DEFINE_OBJECT_UNSET({args[0]}_Oot)")
        else:
            # Objects are loaded by asset path in the port, so the segment name only labels the entry.
            lines.append(f"/* 0x{oot_id:03X} */ DEFINE_OBJECT({args[0]}_Oot, {args[1]}_Oot)")
    return "\n".join(lines) + "\n", expected


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("soh_tables", help="SoH's soh/include/tables directory")
    parser.add_argument("--ported", default="", help="comma-separated OoT actor enums that have been ported")
    args = parser.parse_args()
    ported = {p.strip() for p in args.ported.split(",") if p.strip()}

    actors, n_actors = gen_actors(args.soh_tables, ported)
    objects, n_objects = gen_objects(args.soh_tables)
    with open(os.path.join(OUT_DIR, "actor_table_oot.h"), "w") as f:
        f.write(actors)
    with open(os.path.join(OUT_DIR, "object_table_oot.h"), "w") as f:
        f.write(objects)
    print(f"{n_actors} actors and {n_objects} objects written to {os.path.normpath(OUT_DIR)}")


if __name__ == "__main__":
    main()
