#!/usr/bin/env python3
"""Generate the OoT parts of 2Ship's actor, object and item id tables from SoH's headers.

OoT entries follow MM's in OoT's own order, so a unified id is ACTOR_OOT_BASE or OBJECT_OOT_BASE (see
hyrule/HyruleIds.h) plus the OoT id. Names get an _Oot suffix. Actors that have not been ported are
DEFINE_ACTOR_UNSET, so their ids exist but cannot spawn; a ported actor's line is kept by passing its
OoT enum name to --ported.

It also writes hyrule/HyruleScenesPending.h, which names the OoT scenes the scene table lacks so ported
code can refer to them.

Item ids work the same way above ITEM_OOT_BASE; only OoT's own items (up to ITEM_NUT_UPGRADE_40) are
included, not SoH's additions or OoT's special values.

    python3 tools/porting/gen_oot_tables.py ../Shipwright/soh/include/tables
"""
import argparse
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, "..", "..", "mm", "include", "tables")
ENTRY = re.compile(r"^/\* (0x[0-9A-Fa-f]+) \*/ (DEFINE_[A-Z_]+)\((.*)\)\s*(//.*)?$")

HEADER = """/**
 * 3Ship [Hyrule] {what} from Ocarina of Time, appended to MM's (see {mm_table}).
 *
 * Generated by tools/porting/gen_oot_tables.py from SoH's {soh_table}. Do not edit by hand.
 * Unified id = {base} (hyrule/HyruleIds.h) + the OoT id shown in each comment.
 */
"""


def entries(path):
    for line in open(path):
        m = ENTRY.match(line.strip())
        if m:
            yield int(m.group(1), 16), m.group(2), [a.strip() for a in m.group(3).split(",")]


def gen_actors(soh_dir, ported):
    lines = [HEADER.format(what="Actors", mm_table="actor_table.h", soh_table="actor_table.h", base="ACTOR_OOT_BASE")]
    expected = 0
    for oot_id, kind, args in entries(os.path.join(soh_dir, "actor_table.h")):
        assert oot_id == expected, f"actor ids must be consecutive (0x{oot_id:X})"
        expected += 1
        enum = args[0] if kind == "DEFINE_ACTOR_UNSET" else args[1]
        enum_oot = f"{enum}_Oot"
        if kind != "DEFINE_ACTOR_UNSET" and enum in ported:
            name, alloc = args[0], args[2]
            lines.append(f'/* 0x{oot_id:03X} */ DEFINE_ACTOR({name}_Oot, {enum_oot}, {alloc}, "{name}_Oot", "{name} (OoT)")')
        else:
            lines.append(f"/* 0x{oot_id:03X} */ DEFINE_ACTOR_UNSET({enum_oot})")
    return "\n".join(lines) + "\n", expected


def gen_objects(soh_dir):
    lines = [HEADER.format(what="Objects", mm_table="object_table.h", soh_table="object_table.h", base="OBJECT_OOT_BASE")]
    expected = 0
    for oot_id, kind, args in entries(os.path.join(soh_dir, "object_table.h")):
        assert oot_id == expected, f"object ids must be consecutive (0x{oot_id:X})"
        expected += 1
        if kind == "DEFINE_OBJECT_UNSET":
            lines.append(f"/* 0x{oot_id:03X} */ DEFINE_OBJECT_UNSET({args[0]}_Oot)")
        else:
            # Objects are loaded by asset path in the port, so the segment name only labels the entry.
            lines.append(f"/* 0x{oot_id:03X} */ DEFINE_OBJECT({args[0]}_Oot, {args[1]}_Oot)")
    return "\n".join(lines) + "\n", expected


ITEM_ENTRY = re.compile(r"^/\* (0x[0-9A-Fa-f]+) \*/ (ITEM_\w+)\s*(=\s*\w+)?,?\s*(//.*)?$")
LAST_OOT_ITEM = "ITEM_NUT_UPGRADE_40"


def gen_items(soh_include):
    lines = [
        "/**",
        " * 3Ship [Hyrule] Item ids from Ocarina of Time, placed after MM's inside the ItemId enum (z64item.h).",
        " *",
        " * Generated by tools/porting/gen_oot_tables.py from SoH's z64item.h. Do not edit by hand.",
        " * Unified id = ITEM_OOT_BASE (hyrule/HyruleIds.h) + the OoT id shown in each comment.",
        " */",
    ]
    text = open(os.path.join(soh_include, "z64item.h")).read()
    body = text[text.index("ITEM_STICK,") - 20 : text.index("} ItemID;")]
    expected = 0
    for raw in body.splitlines():
        m = ITEM_ENTRY.match(raw.strip())
        if not m:
            continue
        oot_id, name = int(m.group(1), 16), m.group(2)
        assert oot_id == expected, f"item ids must be consecutive (0x{oot_id:X})"
        expected += 1
        lines.append(f"    /* 0x{oot_id:02X} */ {name}_Oot = ITEM_OOT_BASE + 0x{oot_id:02X},")
        if name == LAST_OOT_ITEM:
            break
    return "\n".join(lines) + "\n", expected


SCENE_ENTRY = re.compile(r"^/\* (0x[0-9A-Fa-f]+) \*/ DEFINE_SCENE\((\w+),\s*\w+,\s*(\w+)")
PENDING_SCENES = os.path.join(HERE, "..", "..", "hyrule", "HyruleScenesPending.h")


def gen_pending_scenes(soh_dir):
    """Ported code names OoT scenes this fork does not have yet; give each an id no scene uses."""
    ours = open(os.path.join(OUT_DIR, "scene_table.h")).read()
    lines = [
        "#pragma once",
        "",
        "// 3Ship [Hyrule] OoT scenes that are not in the scene table yet. Each gets a distinct negative id, so",
        "// ported code that checks for one compiles and never matches. A scene drops out of this list once it",
        "// is added to mm/include/tables/scene_table.h.",
        "//",
        "// Generated by tools/porting/gen_oot_tables.py from SoH's scene_table.h. Do not edit by hand.",
        "",
    ]
    count = 0
    for line in open(os.path.join(soh_dir, "scene_table.h")):
        m = SCENE_ENTRY.match(line.strip())
        if m and f"{m.group(3)}_Oot," not in ours:
            lines.append(f"#define {m.group(3)}_Oot (-2 - {m.group(1)})")
            count += 1
    with open(PENDING_SCENES, "w") as f:
        f.write("\n".join(lines) + "\n")
    return count


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("soh_tables", help="SoH's soh/include/tables directory")
    parser.add_argument("--ported", default="", help="comma-separated OoT actor enums that have been ported")
    args = parser.parse_args()
    ported = {p.strip() for p in args.ported.split(",") if p.strip()}

    actors, n_actors = gen_actors(args.soh_tables, ported)
    objects, n_objects = gen_objects(args.soh_tables)
    items, n_items = gen_items(os.path.join(args.soh_tables, ".."))
    with open(os.path.join(OUT_DIR, "actor_table_oot.h"), "w") as f:
        f.write(actors)
    with open(os.path.join(OUT_DIR, "object_table_oot.h"), "w") as f:
        f.write(objects)
    with open(os.path.join(OUT_DIR, "item_id_oot.h"), "w") as f:
        f.write(items)
    pending = gen_pending_scenes(args.soh_tables)
    print(f"{n_actors} actors, {n_objects} objects and {n_items} items written to {os.path.normpath(OUT_DIR)}, "
          f"{pending} scenes still pending")


if __name__ == "__main__":
    main()
